// Emits sw.js at build time: it precaches the app shell (every hashed file Vite produced) and handles audio and fonts at runtime,
// so the app opens and works offline once visited. Hand-rolled to keep the dependency list short.
import { createHash } from 'node:crypto'

const PUBLIC_FILES = ['manifest.webmanifest', 'favicon.svg', 'icon-192.png', 'icon-512.png', 'icon-maskable-512.png', 'apple-touch-icon.png']

const worker = (shell, version) => `// generated by build/sw-plugin.js — do not edit
const VERSION = ${JSON.stringify(version)}
const SHELL = 'lb-shell-' + VERSION
const AUDIO = 'lb-audio'
const FONTS = 'lb-fonts'
const BASE = self.registration.scope
const PRECACHE = ${JSON.stringify(shell)}.map((f) => new URL(f, BASE).href)
const INDEX = new URL('./', BASE).href // the app's start page, precached above

self.addEventListener('install', (e) => {
  e.waitUntil(caches.open(SHELL).then((c) => c.addAll(PRECACHE)).then(() => self.skipWaiting()))
})

self.addEventListener('activate', (e) => {
  e.waitUntil(
    caches
      .keys()
      .then((keys) => Promise.all(keys.filter((k) => k.startsWith('lb-shell-') && k !== SHELL).map((k) => caches.delete(k))))
      .then(() => self.clients.claim()),
  )
})

// Safari (and seeking in any browser) asks audio for byte ranges: answer them from the full cached file.
async function ranged(req, res) {
  const h = req.headers.get('range')
  if (!h || res.status !== 200) return res
  const m = /bytes=(\\d*)-(\\d*)/.exec(h)
  if (!m) return res
  const buf = await res.arrayBuffer()
  const size = buf.byteLength
  let start = m[1] ? Number(m[1]) : 0
  let end = m[2] ? Number(m[2]) : size - 1
  if (!m[1] && m[2]) {
    start = Math.max(0, size - Number(m[2]))
    end = size - 1
  }
  end = Math.min(end, size - 1)
  return new Response(buf.slice(start, end + 1), {
    status: 206,
    headers: { 'Content-Type': 'audio/mpeg', 'Content-Range': 'bytes ' + start + '-' + end + '/' + size, 'Content-Length': String(end - start + 1), 'Accept-Ranges': 'bytes' },
  })
}

async function audio(req) {
  const cache = await caches.open(AUDIO)
  let res = await cache.match(req.url, { ignoreVary: true })
  if (!res) {
    try {
      const net = await fetch(req.url) // always the whole file, even when the player asked for a range
      if (!net.ok) return net
      cache.put(req.url, net.clone())
      res = net
    } catch {
      return Response.error()
    }
  }
  return ranged(req, res)
}

async function networkFirst(req, cacheName, fallbackKey) {
  const cache = await caches.open(cacheName)
  try {
    const net = await fetch(req)
    if (net.ok) cache.put(fallbackKey ?? req, net.clone())
    return net
  } catch {
    return (await cache.match(fallbackKey ?? req, { ignoreVary: true })) ?? Response.error()
  }
}

async function staleWhileRevalidate(req, cacheName) {
  const cache = await caches.open(cacheName)
  const hit = await cache.match(req, { ignoreVary: true })
  const net = fetch(req)
    .then((res) => {
      if (res.ok || res.type === 'opaque') cache.put(req, res.clone())
      return res
    })
    .catch(() => null)
  return hit ?? (await net) ?? Response.error()
}

self.addEventListener('fetch', (e) => {
  const req = e.request
  if (req.method !== 'GET') return
  const url = new URL(req.url)

  if (url.origin === self.location.origin) {
    if (url.pathname.endsWith('/audio/manifest.json')) return e.respondWith(networkFirst(req, AUDIO))
    if (url.pathname.includes('/audio/') && url.pathname.endsWith('.mp3')) return e.respondWith(audio(req))
    if (req.mode === 'navigate') {
      // online: always the newest page; offline: the cached app, which then routes the URL itself
      return e.respondWith(
        fetch(req).catch(() => caches.open(SHELL).then((c) => c.match(INDEX, { ignoreVary: true })).then((r) => r ?? Response.error())),
      )
    }
    return e.respondWith(caches.match(req, { ignoreSearch: true, ignoreVary: true }).then((r) => r ?? fetch(req)))
  }
  if (url.hostname === 'fonts.googleapis.com' || url.hostname === 'fonts.gstatic.com') return e.respondWith(staleWhileRevalidate(req, FONTS))
})
`

export default function serviceWorker() {
  return {
    name: 'lb-service-worker',
    apply: 'build',
    generateBundle(_, bundle) {
      const built = Object.keys(bundle).filter((f) => !f.endsWith('.map'))
      const shell = ['./', ...built, ...PUBLIC_FILES]
      const version = createHash('sha1').update(built.join('|')).digest('hex').slice(0, 10)
      this.emitFile({ type: 'asset', fileName: 'sw.js', source: worker(shell, version) })
    },
  }
}
